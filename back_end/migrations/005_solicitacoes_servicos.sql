-- Evidências privadas; nenhuma solicitação altera a oferta antes da revisão.
CREATE TABLE solicitacoes_servicos (
 id INT NOT NULL AUTO_INCREMENT,
 usuario_id INT NULL,
 posto_id INT NOT NULL,
 combustivel_codigo VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 chave_cliente CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 foto_arquivo VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 foto_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 observacao VARCHAR(500) NOT NULL,
 distancia_m DECIMAL(10,2) NOT NULL,
 precisao_m DECIMAL(10,2) NOT NULL,
 estado VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pendente',
 criado_em DATETIME NOT NULL,
 revisado_em DATETIME NULL,
 revisado_por INT NULL,
 motivo VARCHAR(500) NULL,
 PRIMARY KEY (id),
 UNIQUE KEY uq_ss_usuario_chave (usuario_id,chave_cliente),
 UNIQUE KEY uq_ss_foto (foto_arquivo),
 KEY idx_ss_estado_id (estado,id),
 KEY idx_ss_usuario_id (usuario_id,id),
 KEY idx_ss_posto (posto_id),
 KEY idx_ss_produto (combustivel_codigo),
 KEY idx_ss_revisor (revisado_por),
 CONSTRAINT ck_ss_estado CHECK (estado IN ('pendente','aprovada','rejeitada')),
 CONSTRAINT fk_ss_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 CONSTRAINT fk_ss_posto FOREIGN KEY (posto_id) REFERENCES postos(id) ON DELETE CASCADE,
 CONSTRAINT fk_ss_produto FOREIGN KEY (combustivel_codigo) REFERENCES combustiveis(codigo),
 CONSTRAINT fk_ss_revisor FOREIGN KEY (revisado_por) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;